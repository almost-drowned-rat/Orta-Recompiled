/* launcher/main.c -- "orta_launcher.exe" (until v1.2.2 "Panzer Dragoon Orta Recomp.exe"), the one file a player
 * downloads: the toolkit's launcher (src/launcher) with Orta's names, versions and icon. The release script
 * (tools/release.ps1) appends the payload to the built exe. Model: THPS 2X launcher/main.c.
 *
 * From v1.3.0 (maintainer 2026-11-23: every port's launcher in the designs of option-p's launcher) Windows and Linux
 * run the toolkit's port launcher (option-c launcher_port.h, xr_launcher_port_main): Windows = option-p's window in
 * Windows 95's look (port_setup_ui_win95.c), Linux = the same in Windows 2000's look (port_setup_ui_win2000_sdl.c).
 * A fresh start without arguments shows the first page (disc image, "Install to:", Go / Quit); the build's progress
 * runs in the same window, then the game starts. Another folder gets a copy of the launcher (+ tools\bundle\, the media
 * README), started there with --image. Installed folders, --repair, --image and RECOMP_NO_DIALOGS=1 go to the
 * toolkit's launcher. The launcher's Vulkan 1.3 check is the toolkit's (xr_port_vk_gate); the game keeps its own
 * (src/vk_check.c). Orta's own setup window (launcher/setup_win32.c, v1.0 - v1.2.2) is gone.
 *
 * Android (the APK's loader, libORTA_game.so) keeps the toolkit's launcher with Orta's own progress UI
 * (launcher/setup_ui_sdl.c) and the Vulkan check of src/vk_check.c. */

